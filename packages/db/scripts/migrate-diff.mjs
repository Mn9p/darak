// Generates / refreshes the PostgreSQL migration SQL from the schema without touching any database.
// Usage: node scripts/migrate-diff.mjs [name]   (default: 0001_init)
// Read-only: uses `prisma migrate diff --from-empty --to-schema-datamodel`. Never runs `migrate dev`.
import { mkdirSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { spawnSync } from "node:child_process";
import { syncProvider, SCHEMA_DIR, PKG_ROOT, providerFor, loadEnv } from "./env.mjs";

const name = process.argv[2] ?? "0001_init";
const url = loadEnv();
const original = providerFor(url);

syncProvider("postgresql");
try {
  const bin = process.platform === "win32" ? "npx.cmd" : "npx";
  const res = spawnSync(bin, ["prisma", "migrate", "diff", "--from-empty", "--to-schema-datamodel", SCHEMA_DIR, "--script"], {
    cwd: PKG_ROOT,
    encoding: "utf8",
    shell: process.platform === "win32",
    env: { ...process.env, DATABASE_URL: "postgresql://diff:diff@localhost:5432/diff" },
  });
  if (res.status !== 0) {
    console.error(res.stderr || res.stdout);
    process.exit(res.status ?? 1);
  }
  const dir = resolve(SCHEMA_DIR, "migrations", name);
  mkdirSync(dir, { recursive: true });
  writeFileSync(resolve(dir, "migration.sql"), res.stdout);
  writeFileSync(resolve(SCHEMA_DIR, "migrations/migration_lock.toml"), '# Please do not edit this file manually\n# It should be added in your version-control system (e.g., Git)\nprovider = "postgresql"\n');
  console.log(`[db] wrote prisma/schema/migrations/${name}/migration.sql (${res.stdout.split("\n").length} lines)`);
} finally {
  syncProvider(original);
}
